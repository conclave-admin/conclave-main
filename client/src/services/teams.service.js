import { api } from '../lib/api';
const data = async (request) => (await request).data.data;
export const listTeams = () => data(api.get('/teams'));
export const getTeam = (id) => data(api.get(`/teams/${id}`));
export const createTeam = (payload) => data(api.post('/teams',payload));
export const updateTeam = (id,payload) => data(api.patch(`/teams/${id}`,payload));
export const createTeamRoom = (id,payload) => data(api.post(`/teams/${id}/rooms`,payload));
export const createTeamProject = (id,payload) => data(api.post(`/teams/${id}/projects`,payload));
export const createInvite = (id,payload) => data(api.post(`/teams/${id}/invites`,payload));
export const revokeInvite = (id,inviteId) => data(api.delete(`/teams/${id}/invites/${inviteId}`));
export const previewInvite = (token) => data(api.post('/teams/invites/preview',{token}));
export const acceptInvite = (token) => data(api.post('/teams/invites/accept',{token}));
export const archiveTeam = (id) => data(api.post(`/teams/${id}/archive`));
export const restoreTeam = (id) => data(api.post(`/teams/${id}/restore`));
export const leaveTeam = (id) => data(api.post(`/teams/${id}/leave`));
export const removeMember = (id,userId) => data(api.delete(`/teams/${id}/members/${userId}`));
export const setRole = (id,userId,role) => data(api.patch(`/teams/${id}/members/${userId}`,{role}));
export const transferOwner = (id,userId) => data(api.post(`/teams/${id}/transfer-owner`,{userId}));
export const previewTransfer = (id,params) => data(api.get(`/teams/${id}/transfer-preview`,{params}));
export const moveRoom = (id,roomId) => data(api.post(`/teams/${id}/rooms/${roomId}`));
export const moveProject = (id,projectId) => data(api.post(`/teams/${id}/projects/${projectId}`));
export const requestDiscovery = (roomId) => data(api.post(`/teams/discovery-requests/${roomId}`));
export const reviewRequest = (id,userId,decision) => data(api.post(`/teams/${id}/requests/${userId}`,{decision}));
export const setRoomDiscovery = (id,roomId,discoverable) => data(api.patch(`/teams/${id}/rooms/${roomId}/discovery`,{discoverable}));
